create or replace function public.business_finalize_razorpay_event(
  p_event_id text,p_event_type text,p_payment_id text,p_order_id text,p_payload_hash text,p_action text
) returns boolean language plpgsql security definer set search_path=''
as $$
declare v_order public.business_payment_orders%rowtype;
begin
  if p_action not in ('activate','fail','refund','dispute','ignore') then raise exception 'Invalid payment action'; end if;
  insert into public.business_payment_webhook_events(provider_event_id,event_type,provider_payment_id,payload_hash)
  values(p_event_id,p_event_type,p_payment_id,p_payload_hash) on conflict(provider_event_id) do nothing;
  if not found then return false; end if;
  select * into v_order from public.business_payment_orders where provider_order_id=p_order_id for update;
  if v_order.id is null then
    update public.business_payment_webhook_events set processed_at=now() where provider_event_id=p_event_id;
    return true;
  end if;
  if p_action='activate' then
    update public.business_payment_orders set provider_payment_id=p_payment_id,status='captured',verified_at=now() where id=v_order.id;
    update public.business_payment_proposals set status='paid',updated_at=now() where id=v_order.proposal_id and organization_id=v_order.organization_id;
    update public.business_organizations set payment_status='gateway_confirmed',pilot_access_status='active',access_updated_at=now() where id=v_order.organization_id;
  elsif p_action in ('fail','refund','dispute') then
    update public.business_payment_orders set provider_payment_id=coalesce(provider_payment_id,p_payment_id),status=p_event_type where id=v_order.id;
    update public.business_organizations set payment_status=case when p_action='refund' then 'refunded' else 'unpaid' end,pilot_access_status='revoked',access_updated_at=now() where id=v_order.organization_id;
  end if;
  update public.business_payment_webhook_events set processed_at=now() where provider_event_id=p_event_id;
  return true;
end $$;
revoke all on function public.business_finalize_razorpay_event(text,text,text,text,text,text) from public,anon,authenticated;
grant execute on function public.business_finalize_razorpay_event(text,text,text,text,text,text) to service_role;

create or replace function public.business_has_effective_access(p_organization_id uuid,p_user_id uuid default auth.uid(),p_require_membership boolean default true)
returns boolean language sql stable security definer set search_path=''
as $$ select exists(select 1 from public.business_organizations o where o.id=p_organization_id and o.status in ('pilot','active')
 and o.pilot_access_status='active' and o.payment_status in ('manual_confirmed','gateway_confirmed','waived')
 and (o.access_expires_at is null or o.access_expires_at>now() or (o.access_grace_until is not null and o.access_grace_until>now()))
 and (not p_require_membership or (p_user_id is not null and exists(select 1 from public.business_organization_members m where m.organization_id=o.id and m.user_id=p_user_id)))) $$;
revoke all on function public.business_has_effective_access(uuid,uuid,boolean) from public,anon;
grant execute on function public.business_has_effective_access(uuid,uuid,boolean) to authenticated,service_role;
