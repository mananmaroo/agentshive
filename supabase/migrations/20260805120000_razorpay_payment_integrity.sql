alter table public.business_organizations add column if not exists billing_country text;
alter table public.business_organizations drop constraint if exists business_organizations_payment_status_check;
alter table public.business_organizations add constraint business_organizations_payment_status_check
  check (payment_status in ('unpaid','manual_confirmed','gateway_confirmed','waived','refunded'));

create table if not exists public.business_payment_proposals (
  id uuid primary key default gen_random_uuid(), organization_id uuid not null references public.business_organizations(id) on delete cascade,
  price_book_id text not null check (price_book_id ~ '^[a-z0-9_]{3,40}$'), billing_country text not null check (billing_country ~ '^[A-Z]{2}$'),
  customer_email text, status text not null default 'draft' check (status in ('draft','approved','paid','expired','cancelled')),
  expires_at timestamptz not null, created_by uuid references auth.users(id), created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.business_payment_orders (
  id uuid primary key default gen_random_uuid(), organization_id uuid not null references public.business_organizations(id) on delete cascade,
  proposal_id uuid not null references public.business_payment_proposals(id), created_by uuid not null references auth.users(id),
  provider_order_id text not null unique, provider_payment_id text unique, receipt text not null unique check (char_length(receipt) <= 40),
  amount bigint not null check (amount >= 100), currency text not null check (currency ~ '^[A-Z]{3}$'),
  idempotency_key text not null, status text not null check (char_length(status) between 3 and 80),
  verified_at timestamptz, created_at timestamptz not null default now(), unique(created_by,idempotency_key)
);
create table if not exists public.business_payment_webhook_events (
  id bigint generated by default as identity primary key, provider_event_id text not null unique,
  event_type text not null, provider_payment_id text, payload_hash text not null check (payload_hash ~ '^[a-f0-9]{64}$'),
  received_at timestamptz not null default now(), processed_at timestamptz
);
create index if not exists business_payment_orders_org_created_idx on public.business_payment_orders(organization_id,created_at desc);
create index if not exists business_payment_proposals_org_status_idx on public.business_payment_proposals(organization_id,status,expires_at);

