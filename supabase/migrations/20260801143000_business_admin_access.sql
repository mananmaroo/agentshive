do $$
begin
  if not exists (select 1 from pg_constraint where conname='business_organizations_employee_type_check') then
    alter table public.business_organizations add constraint business_organizations_employee_type_check
      check (employee_type in ('aarya_admissions','kabir_lead_followup'));
  end if;
  if not exists (select 1 from pg_constraint where conname='business_organizations_access_status_check') then
    alter table public.business_organizations add constraint business_organizations_access_status_check
      check (pilot_access_status in ('pending','active','revoked','expired'));
  end if;
  if not exists (select 1 from pg_constraint where conname='business_organizations_plan_check') then
    alter table public.business_organizations add constraint business_organizations_plan_check
      check (plan_code in ('pilot','starter','growth','custom'));
  end if;
  if not exists (select 1 from pg_constraint where conname='business_organizations_payment_status_check') then
    alter table public.business_organizations add constraint business_organizations_payment_status_check
      check (payment_status in ('unpaid','manual_confirmed','waived','refunded'));
  end if;
end $$;

