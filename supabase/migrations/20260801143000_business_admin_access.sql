  add column if not exists employee_type text not null default 'aarya_admissions',
  add column if not exists pilot_access_status text not null default 'pending',
  add column if not exists access_expires_at timestamptz,
  add column if not exists plan_code text not null default 'pilot',
  add column if not exists payment_status text not null default 'unpaid',
