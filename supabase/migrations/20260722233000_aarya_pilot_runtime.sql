create or replace function public.business_ensure_organization(p_name text,p_root_url text) returns uuid
language plpgsql security definer set search_path=''
as $$
declare v_user uuid := auth.uid(); v_org uuid;
begin
 if v_user is null then raise exception 'Authentication required'; end if;
 if char_length(trim(p_name)) < 2 or char_length(trim(p_name)) > 160 then raise exception 'Invalid organization name'; end if;
 if p_root_url !~ '^https?://' then raise exception 'Invalid organization URL'; end if;
 select organization_id into v_org from public.business_organization_members where user_id=v_user order by created_at limit 1;
 if v_org is null then
   insert into public.business_organizations(name,root_url) values(trim(p_name),trim(p_root_url)) returning id into v_org;
   insert into public.business_organization_members(organization_id,user_id,role) values(v_org,v_user,'owner');
 else
   update public.business_organizations set name=trim(p_name),root_url=trim(p_root_url),updated_at=now() where id=v_org;
 end if;
 return v_org;
end $$;

create or replace function public.aarya_get_approved_knowledge(p_widget_key uuid)
returns table(organization_id uuid,organization_name text,source_url text,title text,content text)
language sql stable security definer set search_path=''
as $$ select o.id,o.name,k.source_url,k.title,k.content from public.business_organizations o join public.business_approved_knowledge k on k.organization_id=o.id where o.widget_key=p_widget_key and o.status in ('pilot','active') and k.approved order by k.updated_at desc limit 10 $$;

create or replace function public.aarya_record_exchange(
 p_widget_key uuid,p_conversation_id uuid,p_question text,p_answer text,p_needs_human boolean,
 p_source_urls text[] default '{}',p_visitor_name text default null,p_visitor_email text default null,
 p_visitor_phone text default null,p_course_interest text default null) returns uuid
language plpgsql security definer set search_path=''
as $$
declare v_org uuid; v_conversation uuid;
begin
 if char_length(trim(p_question)) not between 1 and 2000 then raise exception 'Invalid question'; end if;
 if char_length(trim(p_answer)) not between 1 and 5000 then raise exception 'Invalid answer'; end if;
 select id into v_org from public.business_organizations where widget_key=p_widget_key and status in ('pilot','active');
 if v_org is null then raise exception 'Unknown widget'; end if;
 if p_conversation_id is not null then select id into v_conversation from public.business_conversations where id=p_conversation_id and organization_id=v_org; end if;
 if v_conversation is null then
   insert into public.business_conversations(organization_id,visitor_name,visitor_email,visitor_phone,status)
   values(v_org,nullif(trim(p_visitor_name),''),nullif(lower(trim(p_visitor_email)),''),nullif(trim(p_visitor_phone),''),case when p_needs_human then 'needs_attention' else 'open' end) returning id into v_conversation;
 else
   update public.business_conversations set last_message_at=now(),status=case when p_needs_human then 'needs_attention' else status end,
   visitor_name=coalesce(nullif(trim(p_visitor_name),''),visitor_name),visitor_email=coalesce(nullif(lower(trim(p_visitor_email)),''),visitor_email),visitor_phone=coalesce(nullif(trim(p_visitor_phone),''),visitor_phone) where id=v_conversation;
 end if;
 insert into public.business_messages(conversation_id,sender,content) values(v_conversation,'visitor',trim(p_question));
 insert into public.business_messages(conversation_id,sender,content,source_urls,needs_human) values(v_conversation,'aarya',trim(p_answer),coalesce(p_source_urls,'{}'),p_needs_human);
 if p_needs_human then insert into public.business_attention_items(organization_id,conversation_id,reason) values(v_org,v_conversation,'Aarya could not safely answer from approved knowledge or the visitor requested human review.'); end if;
 if nullif(trim(p_visitor_name),'') is not null or nullif(trim(p_visitor_email),'') is not null or nullif(trim(p_visitor_phone),'') is not null then
   insert into public.business_leads(organization_id,conversation_id,name,email,phone,course_interest) values(v_org,v_conversation,nullif(trim(p_visitor_name),''),nullif(lower(trim(p_visitor_email)),''),nullif(trim(p_visitor_phone),''),nullif(trim(p_course_interest),''));
 end if;
 return v_conversation;
end $$;

