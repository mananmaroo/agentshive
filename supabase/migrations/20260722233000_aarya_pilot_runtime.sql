-- Aarya controlled-pilot runtime.
-- Schema-only and safe to re-run: no secrets, credentials, or environment-specific seed data.

create extension if not exists pgcrypto with schema extensions;

create table if not exists public.business_organizations (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 2 and 160),
  root_url text not null check (root_url ~ '^https?://'),
  widget_key uuid not null unique default gen_random_uuid(),
  status text not null default 'pilot' check (status in ('pilot','active','paused','archived')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.business_organization_members (
  organization_id uuid not null references public.business_organizations(id) on delete cascade,
  user_id uuid not null references public.users(id) on delete cascade,
  role text not null default 'owner' check (role in ('owner','admin','reviewer')),
  created_at timestamptz not null default now(),
  primary key (organization_id,user_id)
);

create table if not exists public.business_approved_knowledge (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.business_organizations(id) on delete cascade,
  source_url text not null check (source_url ~ '^https?://'),
  title text not null default '',
  content text not null check (char_length(content) between 1 and 50000),
  approved boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (organization_id,source_url)
);

create table if not exists public.business_conversations (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.business_organizations(id) on delete cascade,
  channel text not null default 'website' check (channel in ('website','email','voice')),
  visitor_name text,
  visitor_email text,
  visitor_phone text,
  status text not null default 'open' check (status in ('open','needs_attention','closed')),
  started_at timestamptz not null default now(),
  last_message_at timestamptz not null default now()
);

create table if not exists public.business_messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.business_conversations(id) on delete cascade,
  sender text not null check (sender in ('visitor','aarya','human')),
  content text not null check (char_length(content) between 1 and 5000),
  source_urls text[] not null default '{}',
  needs_human boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.business_leads (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.business_organizations(id) on delete cascade,
  conversation_id uuid references public.business_conversations(id) on delete set null,
  name text,
  email text,
  phone text,
  course_interest text,
  status text not null default 'new' check (status in ('new','qualified','contacted','closed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (email is not null or phone is not null or name is not null)
);

create table if not exists public.business_attention_items (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.business_organizations(id) on delete cascade,
  conversation_id uuid not null references public.business_conversations(id) on delete cascade,
  reason text not null check (char_length(reason) between 1 and 500),
  status text not null default 'open' check (status in ('open','resolved')),
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);

create index if not exists business_org_members_user_idx on public.business_organization_members(user_id,organization_id);
create index if not exists business_knowledge_org_approved_idx on public.business_approved_knowledge(organization_id) where approved;
create index if not exists business_conversations_org_recent_idx on public.business_conversations(organization_id,last_message_at desc);
create index if not exists business_messages_conversation_recent_idx on public.business_messages(conversation_id,created_at);
create index if not exists business_leads_conversation_idx on public.business_leads(conversation_id);
create index if not exists business_leads_org_recent_idx on public.business_leads(organization_id,created_at desc);
create index if not exists business_attention_conversation_idx on public.business_attention_items(conversation_id);
create index if not exists business_attention_org_status_idx on public.business_attention_items(organization_id,status,created_at desc);

